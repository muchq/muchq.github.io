const countOrder = (G: FiniteGroup, k: number) => range(order(G)).filter(a => elementOrder(G, a) === k).length
const maxOrder = (G: FiniteGroup) => Math.max(...range(order(G)).map(a => elementOrder(G, a)))
const labels = (G: FiniteGroup, xs: readonly number[]) => xs.map(x => G.labels[x]).join(', ')
const stats = (G: FiniteGroup) => JSON.stringify([...orderStatistics(G)])
const yes = (b: boolean) => (b ? '0' : '1') // yesNo: option 0 is Yes
const one = (G: FiniteGroup, label: string) => byLabel(G, label)[0]
const p = (s: string, n: number): Perm => {
  const q = parseCycles(s, n)
  if (!q) throw new Error(s)
  return q
}

const problem = (id: string) => {
  const found = answerProblems.find(q => q.id === id)
  if (!found) throw new Error(`no problem ${id}`)
  return found
}

/** The index of the option whose text is `text`, as typed input. */
const option = (id: string, text: string) => {
  const a = problem(id).answer
  if (a.kind !== 'choice') throw new Error(`${id} is not multiple choice`)
  const i = a.options.indexOf(text)
  if (i < 0) throw new Error(`${id} has no option ${text}`)
  return String(i)
}

/** For "which group is this?" questions: the unique option with G's element orders. */
const matchingGroup = (id: string, G: FiniteGroup) => {
  const a = problem(id).answer
  if (a.kind !== 'choice') throw new Error(`${id} is not multiple choice`)
  const parse = (o: string) => o.normalize('NFKC').split(' × ').map(z => Number(z.replace('Z', '')))
  const hits = a.options.filter(o => stats(product(...parse(o))) === stats(G))
  expect(hits, id).toHaveLength(1)
  return option(id, hits[0])
}

const cosetOrder = (G: FiniteGroup, N: number[], a: number) =>
  elementOrder(quotient(G, N), leftCosets(G, N).findIndex(C => C.includes(a)))

const tupleMaxOrder = (orders: number[]) =>
  orders.reduce<number[][]>((acc, n) => acc.flatMap(t => range(n).map(x => [...t, x])), [[]]).reduce(
    (best, t) => Math.max(best, t.reduce((l, x, i) => { const o = orders[i] / gcd(x, orders[i]); return (l / gcd(l, o)) * o }, 1)),
    1
  )

/** Distinct colorings of `points` under `perms`, by canonical representative. */
const orbitsOfColorings = (perms: readonly Perm[], points: number, colors: number) => {
  const seen = new Set<string>()
  for (let code = 0; code < colors ** points; code++) {
    const c = range(points).map(i => Math.floor(code / colors ** i) % colors)
    seen.add(perms.map(g => range(points).map(i => c[g[i]]).join('')).sort()[0])
  }
  return seen.size
}

/** The permutation group generated by `gens`, by closure. */
const closure = (gens: readonly Perm[]): Perm[] => {
  const found = new Map<string, Perm>()
  const queue: Perm[] = [gens[0].map((_, i) => i)]
  found.set(queue[0].join(), queue[0])
  for (let i = 0; i < queue.length; i++)
    for (const g of gens) {
      const h = compose(g, queue[i])
      if (!found.has(h.join())) {
        found.set(h.join(), h)
        queue.push(h)
      }
    }
  return queue
}

const allowedSylowCounts = (n: number, q: number) => {
  let m = n
  while (m % q === 0) m /= q
  return divisors(m).filter(d => d % q === 1).join(', ')
}

